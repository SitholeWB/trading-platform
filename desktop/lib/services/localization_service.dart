class AppL10n {
  static LanguageOption infoFor(String code) {
    return kSupportedLanguages.firstWhere(
      (l) => l.code == code,
      orElse: () => kSupportedLanguages.first,
    );
  }

  static String activeLanguage = 'en';

  static String tr(String key, [String? fallback]) =>
      t(activeLanguage, key, fallback);

  static String t(String code, String key, [String? fallback]) {
    final dict = _translations[code];
    if (dict != null && dict.containsKey(key)) {
      return dict[key]!;
    }
    final en = _translations['en'];
    if (en != null && en.containsKey(key)) {
      return en[key]!;
    }
    return fallback ?? key;
  }


  static String languagePromptInstruction(String code) {
    if (code == 'en') return '';
    final info = infoFor(code);
    return 'Respond in ${info.englishName} (${info.nativeName}, locale "$code"). Keep technical indicator codes and JSON keys in English.';
  }


